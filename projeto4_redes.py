class ClassificadorTemporal(nn.Module):
    def __init__(self, rnn_type, input_dim, hidden_dim, num_classes, arch_type, dropout=0.2):
        super(ClassificadorTemporal, self).__init__()

        if rnn_type == 'LSTM':
            self.rnn = nn.LSTM(input_dim, hidden_dim, batch_first=True)
        elif rnn_type == 'GRU':
            self.rnn = nn.GRU(input_dim, hidden_dim, batch_first=True)
        else:
            raise ValueError("rnn_type deve ser 'LSTM' ou 'GRU'")

        h = hidden_dim
        h_half = max(1, h // 2)

# As cinco opções variam a quantidade e a largura das camadas ocultas:
        if arch_type == 1:
# 1. Uma camada de saída, sem camadas ocultas.
            layers = [nn.Linear(h, num_classes)]
        elif arch_type == 2:
# 2. Duas camadas ocultas, ambas com metade da largura de h.
            layers = [
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, num_classes)
            ]
        elif arch_type == 3:
# 3. Duas camadas ocultas com a mesma largura de h.
            layers = [
                nn.Linear(h, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, num_classes)
            ]
        elif arch_type == 4:
# 4. Três camadas ocultas: metade, largura completa e metade.
            layers = [
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, num_classes)
            ]
        elif arch_type == 5:
# 5. Quatro camadas ocultas, com as duas centrais mais largas.
            layers = [
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, num_classes)
            ]

        self.fc = nn.Sequential(*layers)

    def forward(self, x):
        out, _ = self.rnn(x)
        ultimo_instante = out[:, -1, :]
        return self.fc(ultimo_instante)


# 3. Treinamento e avaliação

def treinar_modelo(model, train_loader, val_loader, lr, epochs=200):
    model.to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.Adam(model.parameters(), lr=lr)

    historico_loss = {'train': [], 'val': []}

    for epoch in range(epochs):
# Treino: atualiza os pesos a cada lote.
        model.train()
        running_train_loss = 0.0
        for batch_X, batch_y in train_loader:
            batch_X, batch_y = batch_X.to(device), batch_y.to(device)
            optimizer.zero_grad()
            outputs = model(batch_X)
            loss = criterion(outputs, batch_y)
            loss.backward()
            optimizer.step()
            running_train_loss += loss.item() * batch_X.size(0)

        epoch_train_loss = running_train_loss / len(train_loader.dataset)
        historico_loss['train'].append(epoch_train_loss)

# Validação: calcula a perda sem alterar os pesos.
        model.eval()
        running_val_loss = 0.0
        with torch.no_grad():
            for batch_X, batch_y in val_loader:
                batch_X, batch_y = batch_X.to(device), batch_y.to(device)
                outputs = model(batch_X)
                loss = criterion(outputs, batch_y)
                running_val_loss += loss.item() * batch_X.size(0)

        epoch_val_loss = running_val_loss / len(val_loader.dataset)
        historico_loss['val'].append(epoch_val_loss)

    metricas_val = avaliar_modelo(model, val_loader)
    return metricas_val, historico_loss

def avaliar_modelo(model, dataloader):
    model.eval()
    y_true, y_pred = [], []

    with torch.no_grad():
        for batch_X, batch_y in dataloader:
            batch_X = batch_X.to(device)
            outputs = model(batch_X)
            preds = torch.argmax(outputs, dim=1).cpu().numpy()
            y_pred.extend(preds)
            y_true.extend(batch_y.numpy())

    return {
        "Acuracia": accuracy_score(y_true, y_pred),
        "F1_Macro": f1_score(y_true, y_pred, average='macro', zero_division=0),
        "Precisao": precision_score(y_true, y_pred, average='macro', zero_division=0),
        "Recall": recall_score(y_true, y_pred, average='macro', zero_division=0),
        "MCC": matthews_corrcoef(y_true, y_pred),
        "R2": r2_score(y_true, y_pred)
    }


