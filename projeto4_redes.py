def carregar_janelas_engine_fault(csv_path, tamanho_janela=30, passo=10):
    """
    Lê o EngineFaultDB, normaliza as 14 features e cria janelas deslizantes
    separadamente para cada classe de falha ('Fault'), evitando misturar transições.
    - tamanho_janela: quantidade de leituras consecutivas por amostra.
    - passo (stride): deslocamento da janela (passo=10 reduz redundância e acelera o treino).
    """
    df = pd.read_csv(csv_path)

    # Usa Fault como rótulo; se a coluna não existir, considera a última.
    coluna_alvo = 'Fault' if 'Fault' in df.columns else df.columns[-1]

    features_cols = [c for c in df.columns if c != coluna_alvo]

# Padroniza os valores dos sensores antes de criar as janelas.
    scaler = StandardScaler()
    df[features_cols] = scaler.fit_transform(df[features_cols])

    X_list, y_list = [], []

# Cria as janelas por classe para não misturar registros de falhas diferentes.
    for fault_label, group in df.groupby(coluna_alvo):
        valores = group[features_cols].values
        for i in range(0, len(valores) - tamanho_janela + 1, passo):
            X_list.append(valores[i : i + tamanho_janela])
            y_list.append(int(fault_label))

    return np.array(X_list, dtype=np.float32), np.array(y_list, dtype=np.int64)

