def criar_funcao_objetivo(rnn_type):
    def objective(trial):
        arch_type = trial.suggest_int("arch_type", 1, 5)
        hidden_dim = trial.suggest_categorical("hidden_dim", [64, 128, 256])
        lr = trial.suggest_float("lr", 1e-4, 1e-2, log=True)
        dropout = trial.suggest_float("dropout", 0.1, 0.5)

        modelo = ClassificadorTemporal(
            rnn_type=rnn_type,
            input_dim=input_dim,
            hidden_dim=hidden_dim,
            num_classes=num_classes,
            arch_type=arch_type,
            dropout=dropout
        )

        metricas_val, _ = treinar_modelo(modelo, train_loader, val_loader, lr=lr, epochs=200)
        return metricas_val["F1_Macro"]
    return objective

