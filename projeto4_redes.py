class ClassificadorTemporalAvancado(nn.Module):
    def __init__(self, rnn_type, input_dim, hidden_dim, num_classes, arch_type,
                 dropout=0.2, num_layers=1, bidirectional=False):
        super(ClassificadorTemporalAvancado, self).__init__()

        self.bidirectional = bidirectional
# O dropout interno da RNN atua entre camadas e, por isso, exige num_layers > 1.
        rnn_dropout = dropout if num_layers > 1 else 0.0

        if rnn_type == 'LSTM':
            self.rnn = nn.LSTM(
                input_dim, hidden_dim,
                num_layers=num_layers,
                batch_first=True,
                dropout=rnn_dropout,
                bidirectional=bidirectional
            )
        elif rnn_type == 'GRU':
            self.rnn = nn.GRU(
                input_dim, hidden_dim,
                num_layers=num_layers,
                batch_first=True,
                dropout=rnn_dropout,
                bidirectional=bidirectional
            )
        else:
            raise ValueError("rnn_type deve ser 'LSTM' ou 'GRU'")

# Na versão bidirecional, as saídas das duas direções são concatenadas.
        in_fc = hidden_dim * 2 if bidirectional else hidden_dim
        h = hidden_dim
        h_half = max(1, h // 2)

# Camadas densas responsáveis pela classificação.
        if arch_type == 1:
# A entrada tem hidden_dim valores, ou o dobro quando a RNN é bidirecional.
            layers = [nn.Linear(in_fc, num_classes)]
        elif arch_type == 2:
            layers = [
                nn.Linear(in_fc, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, num_classes)
            ]
        elif arch_type == 3:
            layers = [
                nn.Linear(in_fc, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, num_classes)
            ]
        elif arch_type == 4:
            layers = [
                nn.Linear(in_fc, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, num_classes)
            ]
        elif arch_type == 5:
            layers = [
                nn.Linear(in_fc, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h, h_half), nn.ReLU(), nn.Dropout(dropout),
                nn.Linear(h_half, num_classes)
            ]

        self.fc = nn.Sequential(*layers)

    def forward(self, x):
        out, _ = self.rnn(x)
        ultimo_instante = out[:, -1, :]
        return self.fc(ultimo_instante)



