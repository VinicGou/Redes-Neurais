def extract_latent_space(model, dataloader):
    model.eval()
    latents = []
    labels = []
    with torch.no_grad():
        for x_batch, y_batch in dataloader:
            x_batch = x_batch.to(device)
            mu, _ = model.encode(x_batch) # Usamos a média (mu) como representação determinística
            latents.append(mu.cpu().numpy())
            labels.append(y_batch.numpy())
    return np.vstack(latents), np.concatenate(labels)

