class VAE(nn.Module):
    def __init__(self, input_dim=784, hidden_dims=[512, 256], latent_dim=2):
        super(VAE, self).__init__()

        # Construção dinâmica do Encoder
        encoder_layers = []
        in_d = input_dim
        for h_d in hidden_dims:
            encoder_layers.append(nn.Linear(in_d, h_d))
            encoder_layers.append(nn.BatchNorm1d(h_d))
            encoder_layers.append(nn.LeakyReLU(0.2))
            in_d = h_d
        self.encoder = nn.Sequential(*encoder_layers)

        # Camadas do espaço latente (média e log-variância)
        self.fc_mu = nn.Linear(hidden_dims[-1], latent_dim)
        self.fc_logvar = nn.Linear(hidden_dims[-1], latent_dim)

        # Construção dinâmica do Decoder (espelhado)
        decoder_layers = []
        reversed_dims = list(reversed(hidden_dims))
        in_d = latent_dim
        for h_d in reversed_dims:
            decoder_layers.append(nn.Linear(in_d, h_d))
            decoder_layers.append(nn.BatchNorm1d(h_d))
            decoder_layers.append(nn.LeakyReLU(0.2))
            in_d = h_d
        decoder_layers.append(nn.Linear(reversed_dims[-1], input_dim))
        decoder_layers.append(nn.Sigmoid()) # Saída entre [0, 1]
        self.decoder = nn.Sequential(*decoder_layers)

    def encode(self, x):
        h = self.encoder(x)
        return self.fc_mu(h), self.fc_logvar(h)

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        return self.decoder(z)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        recon_x = self.decode(z)
        return recon_x, mu, logvar

# Função de custo ELBO: Reconstrução (BCE) + Divergência KL
def vae_loss_function(recon_x, x, mu, logvar):
    bce = F.binary_cross_entropy(recon_x, x, reduction="sum")
    kld = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())
    return bce + kld

def train_and_evaluate(latent_dim, topologies, epochs=20, lr=1e-3):
    best_val_loss = float("inf")
    best_model = None
    best_topology = None
    history = {}

    for topo_name, hidden_dims in topologies.items():
        print(f"\nTreinando VAE | Latente: {latent_dim}D | Topologia: {topo_name} {hidden_dims}")
        model = VAE(input_dim=784, hidden_dims=hidden_dims, latent_dim=latent_dim).to(device)
        optimizer = torch.optim.Adam(model.parameters(), lr=lr)

        val_losses = []
        for epoch in range(1, epochs + 1):
            # Treino
            model.train()
            for x_batch, _ in train_loader:
                x_batch = x_batch.to(device)
                optimizer.zero_grad()
                recon_batch, mu, logvar = model(x_batch)
                loss = vae_loss_function(recon_batch, x_batch, mu, logvar)
                loss.backward()
                optimizer.step()

            # Validação
            model.eval()
            val_loss = 0.0
            with torch.no_grad():
                for x_batch, _ in val_loader:
                    x_batch = x_batch.to(device)
                    recon_batch, mu, logvar = model(x_batch)
                    val_loss += vae_loss_function(recon_batch, x_batch, mu, logvar).item()

            val_loss /= len(val_loader.dataset)
            val_losses.append(val_loss)

            if epoch % 5 == 0 or epoch == epochs:
                print(f"  Época {epoch:02d}/{epochs:02d} - Val Loss: {val_loss:.2f}")

        final_val_loss = val_losses[-1]
        history[topo_name] = final_val_loss

        if final_val_loss < best_val_loss:
            best_val_loss = final_val_loss
            best_model = model
            best_topology = (topo_name, hidden_dims)

    print(f"\n--> Melhor topologia para {latent_dim}D: {best_topology[0]} {best_topology[1]} (Val Loss: {best_val_loss:.2f})")
    return best_model, best_topology, history

